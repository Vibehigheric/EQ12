#!/bin/bash
# ================================
# EQ12 Prompt Folder Auto-Repair Script
# Scans EQ12 for ANY "prompts" folder
# Creates required base files if missing
# ================================

set -e

ROOT="/workspaces/EQ12"

echo ""
echo "🔍 EQ12 Prompt Folder Auto-Repair System"
echo "========================================"
echo ""

# Find all directories named "prompts"
echo "📁 Scanning for 'prompts' folders..."
PROMPT_FOLDERS=$(find "$ROOT" -type d -name "prompts" 2>/dev/null)

if [ -z "$PROMPT_FOLDERS" ]; then
    echo "❌ No 'prompts' folders found in EQ12"
    exit 0
fi

# Count folders
FOLDER_COUNT=$(echo "$PROMPT_FOLDERS" | wc -l)
echo "✅ Found $FOLDER_COUNT prompts folder(s)"
echo ""

# Required base files
REQUIRED_FILES=(
    "README.md"
    "system_prompt.txt"
    "user_prompt_template.txt"
    "developer_prompt_template.txt"
    "metadata.json"
)

# Process each prompts folder
while IFS= read -r folder; do
    echo "📂 Checking: $folder"

    FOLDER_NAME=$(basename "$(dirname "$folder")")

    for file in "${REQUIRED_FILES[@]}"; do
        FILE_PATH="$folder/$file"

        if [ ! -f "$FILE_PATH" ]; then
            echo "  ➕ Creating: $file"

            case "$file" in
                "README.md")
                    cat > "$FILE_PATH" << EOF
# Prompt Folder: $FOLDER_NAME

This folder is automatically maintained by the EQ12 Prompt Repair System.

## Files:
- \`system_prompt.txt\` - System-level instruction set
- \`user_prompt_template.txt\` - User input structure
- \`developer_prompt_template.txt\` - Developer rules and metadata
- \`metadata.json\` - Folder metadata

## Auto-generated
Created: $(date '+%Y-%m-%d %H:%M:%S')
EOF
                    ;;

                "system_prompt.txt")
                    cat > "$FILE_PATH" << EOF
# System Prompt Template
# Auto-created by EQ12 Prompt Repair Script
# Module: $FOLDER_NAME

This file defines the SYSTEM-level instruction set for this module.

## Purpose
Define the AI agent's role, capabilities, and constraints.

## Instructions
1. Replace this template with your system prompt
2. Define agent personality and tone
3. Set knowledge boundaries
4. Specify output format requirements

## Example
You are an expert $FOLDER_NAME assistant. Your role is to help users with [specific task].

---
Last updated: $(date '+%Y-%m-%d %H:%M:%S')
EOF
                    ;;

                "user_prompt_template.txt")
                    cat > "$FILE_PATH" << EOF
# User Prompt Template
# Auto-created by EQ12 Prompt Repair Script
# Module: $FOLDER_NAME

Define the USER input structure for this module.

## Purpose
Provide a template for user interactions with this AI agent.

## Template Variables
- {user_input} - Main user query
- {context} - Additional context
- {preferences} - User preferences

## Example
Please analyze the following data:
{user_input}

Context: {context}
Preferences: {preferences}

---
Last updated: $(date '+%Y-%m-%d %H:%M:%S')
EOF
                    ;;

                "developer_prompt_template.txt")
                    cat > "$FILE_PATH" << EOF
# Developer Prompt Template
# Auto-created by EQ12 Prompt Repair Script
# Module: $FOLDER_NAME

Define the DEVELOPER-level rules, metadata, and instructions for this module.

## Agent Configuration
- **Model**: gpt-4-turbo / claude-sonnet-4.5
- **Temperature**: 0.7
- **Max Tokens**: 4096
- **Top P**: 0.9

## Tools Available
- Code execution
- Web search
- File operations
- API calls

## Safety Constraints
- No harmful content
- Respect rate limits
- Validate inputs
- Log all operations

## Success Criteria
Define what constitutes a successful response:
1. Accuracy threshold
2. Response time limit
3. Format compliance
4. Error handling

## Example Workflow
1. Receive user input
2. Validate and sanitize
3. Process with AI model
4. Post-process output
5. Return formatted response

---
Last updated: $(date '+%Y-%m-%d %H:%M:%S')
EOF
                    ;;

                "metadata.json")
                    cat > "$FILE_PATH" << EOF
{
  "module": "$FOLDER_NAME",
  "created": "$(date '+%Y-%m-%d %H:%M:%S')",
  "autoGenerated": true,
  "version": "1.0.0",
  "maintainer": "EQ12 System",
  "description": "Auto-generated prompt templates for $FOLDER_NAME module",
  "files": {
    "system_prompt": "system_prompt.txt",
    "user_template": "user_prompt_template.txt",
    "developer_template": "developer_prompt_template.txt"
  },
  "configuration": {
    "model": "gpt-4-turbo",
    "temperature": 0.7,
    "max_tokens": 4096,
    "top_p": 0.9
  },
  "status": "active",
  "last_validated": "$(date '+%Y-%m-%d %H:%M:%S')"
}
EOF
                    ;;
            esac
        else
            echo "  ✅ Found: $file"
        fi
    done

    echo ""
done <<< "$PROMPT_FOLDERS"

echo "✅ EQ12 prompt folder integrity restored"
echo ""
echo "🎯 Summary:"
echo "  • Scanned: $FOLDER_COUNT folder(s)"
echo "  • Required files: ${#REQUIRED_FILES[@]} per folder"
echo "  • Status: All folders validated"
echo ""
