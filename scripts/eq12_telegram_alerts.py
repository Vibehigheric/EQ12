# Simple math functions for parlay calculations


def calculate_parlay_odds(decimal_odds_list: list[float]) -> float:
    """Calculate combined decimal odds for independent parlay"""
    result = 1.0
    for odds in decimal_odds_list:
        result *= odds
    return result


def calculate_expected_value(stake: float, odds: float, true_prob: float) -> float:
    """Calculate expected value of a bet"""
    return (stake * odds * true_prob) - stake


@dataclass
class ParlayAlert:
    """Parlay alert data structure"""

    parlay_legs: list[dict[str, Any]]
    total_odds: float
    roi_multiplier: float
    stake_amount: float
    potential_return: float
    expected_value: float
    confidence_score: float
    timestamp: str
    alert_id: str


class TelegramAlerter:
    """Sends parlay alerts via Telegram Bot API"""

    def __init__(self):
        self.bot_token = os.getenv("TELEGRAM_BOT_TOKEN")
        self.chat_id = os.getenv("TELEGRAM_CHAT_ID")
        self.logger = self._setup_logging()

        if not self.bot_token or not self.chat_id:
            raise ValueError(
                "Missing TELEGRAM_BOT_TOKEN or TELEGRAM_CHAT_ID environment variables")

    def _setup_logging(self) -> logging.Logger:
        """Setup logging configuration"""
        logger = logging.getLogger(__name__)
        logger.setLevel(logging.INFO)

        if not logger.handlers:
            handler = logging.StreamHandler()
            formatter = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")
            handler.setFormatter(formatter)
            logger.addHandler(handler)

        return logger

    async def send_parlay_alert(self, alert: ParlayAlert) -> bool:
        """Send parlay alert to Telegram"""
        try:
            message = self._format_parlay_message(alert)
            return await self._send_telegram_message(message)
        except Exception as e:
            self.logger.error(f"Failed to send parlay alert: {e}")
            return False

    def _format_parlay_message(self, alert: ParlayAlert) -> str:
        """Format parlay data into Telegram message"""
        emoji_map = {"high": "🔥", "medium": "⚡", "low": "📊"}

        # Determine alert level based on ROI
        if alert.roi_multiplier >= 15:
            level = "high"
        elif alert.roi_multiplier >= 10:
            level = "medium"
        else:
            level = "low"

        emoji = emoji_map[level]

        message = f"{emoji} **EQ12 OPTIMAL PARLAY ALERT** {emoji}\n\n"
        message += f"🎯 **ROI Multiplier:** {alert.roi_multiplier:.1f}x\n"
        message += (
            f"💰 **Stake:** ${alert.stake_amount:.0f} → **Return:** "
            f"${alert.potential_return:.0f}\n"
        )
        message += f"📈 **Expected Value:** ${alert.expected_value:.2f}\n"
        message += f"🎲 **Confidence:** {alert.confidence_score:.1f}%\n\n"

        message += "🏈 **PARLAY LEGS:**\n"
        for i, leg in enumerate(alert.parlay_legs, 1):
            message += f"{i}. {leg['team']} {leg['bet_type']}\n"
            message += f"   Odds: {leg['odds']:+.0f} | Line: {leg.get('line', 'N/A')}\n"

        message += f"\n⏰ **Alert Time:** {alert.timestamp}\n"
        message += f"🆔 **Alert ID:** {alert.alert_id[:8]}\n"
        message += "\n*Generated by EQ12 Live Parlay Scanner*"

        return message

    async def _send_telegram_message(self, message: str) -> bool:
        """Send message via Telegram Bot API"""
        url = f"https://api.telegram.org/bot{self.bot_token}/sendMessage"

        payload = {
            "chat_id": self.chat_id,
            "text": message,
            "parse_mode": "Markdown",
            "disable_web_page_preview": True,
        }

        try:
            async with aiohttp.ClientSession() as session:
                async with session.post(url, json=payload) as response:
                    if response.status == 200:
                        self.logger.info("Parlay alert sent successfully")
                        return True
                    else:
                        error_text = await response.text()
                        self.logger.error(
                            f"Telegram API error {
                                response.status}: {error_text}")
                        return False
        except Exception as e:
            self.logger.error(f"Network error sending Telegram message: {e}")
            return False

    async def send_system_status(self, status_type: str = "startup") -> bool:
        """Send system status notification"""
        status_messages = {
            "startup": (
                "🚀 EQ12 Live Parlay Scanner is now active and monitoring "
                "for optimal opportunities!"),
            "shutdown": "⏹️ EQ12 Live Parlay Scanner has stopped monitoring.",
            "error": (
                "⚠️ EQ12 Live Parlay Scanner encountered an error and may "
                "need attention."),
            "health": (
                "✅ EQ12 Live Parlay Scanner health check - all systems "
                "operational."),
        }

        message = status_messages.get(
            status_type, f"📊 EQ12 System Status: {status_type}")
        message += f"\n\n⏰ Time: {datetime.now(UTC).isoformat()}"

        return await self._send_telegram_message(message)

