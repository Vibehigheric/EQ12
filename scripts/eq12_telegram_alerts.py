class ParlayAlertManager:
    """Manages parlay alert generation and sending"""

    def __init__(self):
        self.alerter = TelegramAlerter()
        self.logger = self._setup_logging()
        self.sent_alerts: set = set()  # Track sent alerts to avoid duplicates

    def _setup_logging(self) -> logging.Logger:
        """Setup logging configuration"""
        logger = logging.getLogger(f"{__name__}.manager")
        logger.setLevel(logging.INFO)

        if not logger.handlers:
            handler = logging.StreamHandler()
            formatter = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")
            handler.setFormatter(formatter)
            logger.addHandler(handler)

        return logger

    def create_parlay_alert(
        self,
        parlay_legs: list[dict[str, Any]],
        stake_amount: float = 8.0,
        min_roi_multiplier: float = 10.0,
    ) -> ParlayAlert | None:
        """Create parlay alert from legs data"""
        try:
            # Calculate parlay odds
            odds = [leg["decimal_odds"] for leg in parlay_legs]
            total_odds = calculate_parlay_odds(odds)
            potential_return = stake_amount * total_odds
            roi_multiplier = potential_return / stake_amount

            # Skip if doesn't meet minimum ROI
            if roi_multiplier < min_roi_multiplier:
                return None

            # Calculate expected value (assuming fair market odds)
            true_prob = 1.0 / total_odds  # Convert odds to probability
            expected_value = calculate_expected_value(
                stake_amount, total_odds, true_prob)

            # Calculate confidence score based on various factors
            confidence_score = self._calculate_confidence(parlay_legs, total_odds)

            # Generate unique alert ID
            alert_id = self._generate_alert_id(parlay_legs)

            # Skip if already sent
            if alert_id in self.sent_alerts:
                return None

            alert = ParlayAlert(
                parlay_legs=parlay_legs,
                total_odds=total_odds,
                roi_multiplier=roi_multiplier,
                stake_amount=stake_amount,
                potential_return=potential_return,
                expected_value=expected_value,
                confidence_score=confidence_score,
                timestamp=datetime.now(UTC).isoformat(),
                alert_id=alert_id,
            )

            return alert

        except Exception as e:
            self.logger.error(f"Error creating parlay alert: {e}")
            return None

    def _calculate_confidence(
            self, parlay_legs: list[dict[str, Any]], total_odds: float) -> float:
        """Calculate confidence score for parlay"""
        base_confidence = 70.0

        # Adjust for number of legs (more legs = lower confidence)
        leg_penalty = (len(parlay_legs) - 2) * 5.0
        confidence = base_confidence - leg_penalty

        # Adjust for total odds (very high odds = lower confidence)
        if total_odds > 20:
            odds_penalty = (total_odds - 20) * 0.5
            confidence -= min(odds_penalty, 20.0)

        # Adjust for leg quality (hypothetical scoring)
        for leg in parlay_legs:
            if leg.get("line_movement", 0) > 0:  # Favorable line movement
                confidence += 2.0
            if leg.get("sharp_money", False):  # Sharp money indicator
                confidence += 3.0

        return max(min(confidence, 95.0), 10.0)  # Clamp between 10-95%

    def _generate_alert_id(self, parlay_legs: list[dict[str, Any]]) -> str:
        """Generate unique ID for parlay alert"""
        import hashlib

        # Create hash from parlay legs
        legs_str = json.dumps(
            sorted([f"{leg['team']}_{leg['bet_type']}_{leg['odds']}" for leg in parlay_legs])
        )

        return hashlib.md5(legs_str.encode()).hexdigest()

    async def send_alert(self, alert: ParlayAlert) -> bool:
        """Send parlay alert via Telegram"""
        try:
            success = await self.alerter.send_parlay_alert(alert)
            if success:
                self.sent_alerts.add(alert.alert_id)
                self.logger.info(f"Parlay alert sent: {alert.roi_multiplier:.1f}x ROI")

                # Save alert to log file
                await self._log_alert(alert)

            return success

        except Exception as e:
            self.logger.error(f"Failed to send alert: {e}")
            return False

    async def _log_alert(self, alert: ParlayAlert) -> None:
        """Save alert data to log file"""
        try:
            log_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "logs")
            os.makedirs(log_dir, exist_ok=True)

            log_file = os.path.join(log_dir, "parlay_alerts.json")

            # Read existing alerts
            alerts_data = []
            if os.path.exists(log_file):
                with open(log_file) as f:
                    alerts_data = json.load(f)

            # Add new alert
            alerts_data.append(asdict(alert))

            # Keep only last 100 alerts
            alerts_data = alerts_data[-100:]

            # Write back to file
            with open(log_file, "w") as f:
                json.dump(alerts_data, f, indent=2, default=str)

        except Exception as e:
            self.logger.error(f"Failed to log alert: {e}")


