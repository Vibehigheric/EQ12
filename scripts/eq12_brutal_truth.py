def american_to_decimal(american_odds: int) -> float:
    if american_odds > 0:
        return (american_odds / 100.0) + 1.0
    else:
        return (100.0 / abs(american_odds)) + 1.0

def calculate_parlay(legs_odds: list) -> dict:
    """Calculate true parlay odds."""
    decimal = 1.0
    for odds in legs_odds:
        decimal *= american_to_decimal(odds)
    
    american = int((decimal - 1) * 100) if decimal >= 2 else int(-100/(decimal - 1))
    payout_on_5 = 5.0 * decimal
    profit = payout_on_5 - 5.0
    probability = (1.0 / decimal) * 100
    
    return {
        'decimal': round(decimal, 2),
        'american': american,
        'payout': round(payout_on_5, 2),
        'profit': round(profit, 2),
        'probability': round(probability, 2)
    }

